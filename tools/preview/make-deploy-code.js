// Builds dist (/workspace/a2c-showcase-dist) for the Cloudflare Pages PREVIEW project "a2c-site-preview" and writes the
// code for the Cloudflare API "execute" tool (direct upload: create/patch project, upload assets, create deployment).
// Never targets production (a2c.dev is served by GitHub Pages from main).
// Usage: node tools/preview/make-deploy-code.js, then run the printed file through the Cloudflare API execute tool.
const fs = require('fs'), path = require('path'), { execSync } = require('child_process');
const repo = path.resolve(__dirname, '../..'), out = '/workspace/a2c-showcase-dist';
fs.rmSync(out, { recursive: true, force: true });
for (const f of execSync('git ls-files -co --exclude-standard', { cwd: repo }).toString().split('\n').filter(Boolean)) {
  if (/^(tools\/|CNAME$|\.nojekyll$)/.test(f)) continue;
  fs.mkdirSync(path.join(out, path.dirname(f)), { recursive: true }); fs.copyFileSync(path.join(repo, f), path.join(out, f));
}
fs.copyFileSync(path.join(__dirname, 'robots.txt'), path.join(out, 'robots.txt'));
const CT = { html: 'text/html; charset=utf-8', css: 'text/css; charset=utf-8', js: 'application/javascript; charset=utf-8', svg: 'image/svg+xml', txt: 'text/plain; charset=utf-8', xml: 'application/xml; charset=utf-8' };
const files = []; (function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); fs.statSync(p).isDirectory() ? walk(p) : files.push(p); } })(out);
// Static files are embedded in the preview's _worker.js (the API sandbox cannot use the asset-upload token flow).
const FILES = {};
for (const p of files) { const rel = '/' + path.relative(out, p), ext = path.extname(p).slice(1); FILES[rel] = [CT[ext] || 'application/octet-stream', fs.readFileSync(p, 'utf8')]; }
const worker = `// GENERATED by tools/preview/make-deploy-code.js – preview only (a2c-site-preview). Serves the embedded static site
// with X-Robots-Tag: noindex and forwards /api/* to the a2c-leads Worker (LEADS service binding).
const FILES = ${JSON.stringify(FILES)};
const H = { 'X-Robots-Tag': 'noindex, nofollow', 'Cache-Control': 'public, max-age=60', 'X-Content-Type-Options': 'nosniff', 'Referrer-Policy': 'strict-origin-when-cross-origin' };
export default {
  async fetch(req, env) {
    const u = new URL(req.url);
    if (u.pathname.startsWith('/api/')) { const t = new URL(req.url); t.pathname = u.pathname.slice(4); return env.LEADS.fetch(new Request(t, req)); }
    if (req.method !== 'GET' && req.method !== 'HEAD') return new Response('Method not allowed', { status: 405, headers: H });
    let p = decodeURIComponent(u.pathname);
    if (!FILES[p] && FILES[p + '/index.html']) return Response.redirect(u.origin + p + '/' + u.search, 301);
    if (p.endsWith('/')) p += 'index.html';
    const f = FILES[p];
    if (!f) { const nf = FILES['/404.html']; return new Response(req.method === 'HEAD' ? null : nf[1], { status: 404, headers: { ...H, 'Content-Type': nf[0] } }); }
    return new Response(req.method === 'HEAD' ? null : f[1], { headers: { ...H, 'Content-Type': f[0] } });
  },
};
`;
fs.writeFileSync(path.join(out, '..', 'a2c-showcase-preview-worker.js'), worker);
